#!/usr/bin/env python3
"""Derive scratch/agent/m6_keyed_hold_lldb.sh (lldb-attached mission hold) from m6_keyed_hold_post.sh.

On a VI stall the wrapper SIGINTs lldb (interrupting the game) so 'thread backtrace all' runs at
stall time; on a crash lldb stops and prints the backtrace. Regenerate with this script.
"""
import pathlib
d = pathlib.Path(__file__).resolve().parents[2] / "scratch/agent"
s = (d / "m6_keyed_hold_post.sh").read_text()

def rep(old, new):
    global s
    assert old in s, old
    s = s.replace(old, new, 1)

rep("# M6 keyed endurance:", "# s5455: lldb-attached variant (generated by tools/agent/mk_lldb_hold.py).\n# M6 keyed endurance:")
rep("  ( cd $BUILD && exec env",
    "  /usr/bin/lldb -b -o 'process attach -n RogueSquadron64Recomp -w' -o 'process handle SIGSEGV -s true -n true -p true' "
    "-o 'process handle SIGBUS -s true' -o continue -o 'bt 30' -o 'thread backtrace all' -o 'register read' > $OUT/lldb_att$att.log 2>&1 &\n"
    "  lp=$!; sleep 2\n  ( cd $BUILD && exec env")
rep("cp $L $OUT/fail_att$att.log; }", "cp $L $OUT/fail_att$att.log; kill -9 $lp 2>/dev/null; }")
rep('echo "stall t=$((SECONDS-t0))" >> $K;',
    'echo "stall t=$((SECONDS-t0))" >> $K; [ $stalls -eq 1 ] && { kill -INT $lp 2>/dev/null; sleep 8; echo "lldb interrupted at stall" >> $K; };')
rep("  kill -9 $p 2>/dev/null; wait $p 2>/dev/null\n  echo \"fbhash",
    "  kill -9 $p 2>/dev/null; wait $p 2>/dev/null; kill -9 $lp 2>/dev/null\n"
    "  echo \"lldbstops=$(grep -acE 'stop reason' $OUT/lldb_att$att.log)\" >> $K\n  echo \"fbhash")
(d / "m6_keyed_hold_lldb.sh").write_text(s)
for t in "abc":
    (d / f"soak_queue/m6_lldb_{t}.sh").write_text(
        "#!/bin/zsh\n# s5455: mission hold under lldb attach; stall => bt all, crash => bt. LATE=340 autopilot as s5443.\n"
        'cd "$(git rev-parse --show-toplevel)"\n'
        f"exec env LATE=340 zsh scratch/agent/m6_keyed_hold_lldb.sh s5455_lldb_{t} 520\n")
